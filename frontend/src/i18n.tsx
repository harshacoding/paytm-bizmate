export function translate(text: string, language: Language): string {
  if (language === 'en') return text;
  const row =
    rows.find((row) => row[0] === text) ?? replyTranslations.find((row) => text.startsWith(row[0]));
  return row?.[language === 'hi' ? 1 : 2] ?? text;
}
export function canonical(text: string): string {
  return rows.find((row) => row.some((value) => value === text))?.[0] ?? text;
}
const Context = createContext({
  language: 'en' as Language,
  setLanguage: (_language: Language) => {},
  t: (text: string) => text,
});
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('bizmate-language');
      if (saved === 'hi' || saved === 'te') return saved;
    } catch {}
    return 'en';
  });
  useEffect(() => {
    document.documentElement.lang = language;
    try {
      localStorage.setItem('bizmate-language', language);
    } catch {}
  }, [language]);
  return (
    <Context.Provider value={{ language, setLanguage, t: (text) => translate(text, language) }}>
      {children}
    </Context.Provider>
  );
}
export const useLanguage = () => useContext(Context);
